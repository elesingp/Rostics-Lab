    JSONExtractString (event_json, 'error_code') AS error_code,
    JSONExtractString (event_json, 'category_name') AS category_name,
    JSONExtractString (event_json, 'product_name') AS product_name,
    JSONExtractString (event_json, 'product_id') AS product_id,
    JSONExtractInt (event_json, 'price') AS price,
    JSONExtractString (event_json, 'price_point') AS price_point,
    JSONExtractInt (event_json, 'time_spent') AS time_spent,
    JSONExtractString (event_json, 'modificator_added_flg') AS modificator_added_flg,
    JSONExtractString (event_json, 'modificator_removed_flg') AS modificator_removed_flg,
