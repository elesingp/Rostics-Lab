SELECT
avg(IfNull(added_points_qnt, 0)) as metric
FROM digital_product_analytics.app_metric_events
WHERE toDate(event_datetime) = toDate(date_sub(now(), 1)) AND event_name IN ('system_order_create_success')
ORDER BY metric
CREATE MATERIALIZED VIEW digital_product_analytics.app_metric_consumer
ON CLUSTER '{cluster}'
TO digital_product_analytics.app_metric_events
(
    event_name String,
    event_datetime DateTime,
    event_timestamp UInt32,
    event_json String,
    restaurant_id Int64,
    kiosk_device_id String,
    kiosk_device_name String,
    kiosk_session_id String,
    order_id String,
    session_length Int64,
    language String,
    screen_name String,
    object_type String,
    source_code String,
    authenticated_flg String,
    category_id String,
    product_qnt Int64,
    order_value Int64,
    used_points_qnt Int64,
    added_points_qnt Int64,
    coupon_code String,
    banner_file_name String,
    banner_file_url String,
    link String,
    error_description String,
    error_code String,
    category_name String,
    product_name String,
    product_id String,
