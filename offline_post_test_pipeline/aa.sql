    time_spent UInt32,
    modificator_added_flg String,
    modificator_removed_flg String,
    ingredient_added_flg String,
    ingredient_removed_flg String,
    loyalty_product_flg String,
    modificator_name String,
    modificator_id String,
    ingredient_name String,
    ingredient_id String,
    recommendations String,
    cat_prod_ids Array(String),
