    JSONExtractString (event_json, 'ingredient_id') AS ingredient_id,
    JSONExtractString (event_json, 'recommendations') AS recommendations,
    arrayConcat(
                arrayDistinct(arrayMap(x -> JSONExtractString(JSONExtractRaw(x, toString(indexOf(JSONExtractArrayRaw(recommendations), x) - 1)), 'productId'), JSONExtractArrayRaw(recommendations)))
           ) as cat_prod_ids,
    JSONExtractString (event_json, 'ab_test_name') AS ab_test_name,
    JSONExtractString (event_json, 'ab_test_variant_name') AS ab_test_variant_name,
    event_receive_datetime,
    event_receive_timestamp,
    application_id,
    appmetrica_device_id,
    profile_id,
    session_id AS appmetrica_session_id,
    session_type AS appmetrica_session_type,
   app_version_name,
    app_build_number,
    app_package_name,
    country_iso_code,
    city,
    device_ipv6,
    device_type,
    device_model,
    original_device_model,
    device_manufacturer,
    os_name,
    os_version,
    device_locale,
    connection_type,
    mcc,
    mnc,
    operator_name,
    installation_id,
    android_id,
    google_aid,
    ios_ifa,
    ios_ifv,
    windows_aid,
    stream_window_timestamp,
    parseDateTimeBestEffortOrNull (loaded_at_from_api) AS loaded_at_from_api
FROM digital_product_analytics.app_metric_raw_events_s3queue
