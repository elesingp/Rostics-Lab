) AS
SELECT
    event_name,
    event_datetime,
    event_timestamp,
    event_json,
    JSONExtractInt (event_json, 'restaurant_id') AS restaurant_id,
    JSONExtractString (event_json, 'device_id') AS kiosk_device_id,
    JSONExtractString (event_json, 'device_name') AS kiosk_device_name,
    JSONExtractString (event_json, 'session_id') AS kiosk_session_id,
