    JSONExtractString (event_json, 'coupon_code') AS coupon_code,
    JSONExtractString (event_json, 'banner_file_name') AS banner_file_name,
    JSONExtractString (event_json, 'banner_file_url') AS banner_file_url,
    JSONExtractString (event_json, 'link') AS link,
